case "${NEWERA_LANG:-${LC_ALL:-${LC_MESSAGES:-${LANG:-}}}}" in
    pt*) LANG_TAG=pt ;;
    es*) LANG_TAG=es ;;
    fr*) LANG_TAG=fr ;;
    *) LANG_TAG=en ;;
esac
# t <pt> <en> <es> <fr>
t() {
    case "$LANG_TAG" in
        pt) printf '%s' "$1" ;;
        es) printf '%s' "$3" ;;
        fr) printf '%s' "$4" ;;
        *) printf '%s' "$2" ;;
    esac
}

